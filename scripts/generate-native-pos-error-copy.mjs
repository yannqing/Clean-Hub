import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(
  root,
  "apps/pos-mobile/android/app/src/main/kotlin/com/cleanhub/pos/nativepos/NativePosApiErrorCopy.kt",
);
const messages = new Map();
for (const [file, declaration] of [
  ["tenant-error-messages.ts", "tenantErrorMessages"],
  ["mobile-error-messages.ts", "mobileErrorMessages"],
  ["schema-error-messages.ts", "schemaErrorMessages"],
  ["error-messages.ts", "API_ERROR_MESSAGES"],
]) {
  const source = ts.createSourceFile(
    file,
    fs.readFileSync(path.join(root, "packages/i18n/src", file), "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  function visit(node) {
    if (
      ts.isVariableDeclaration(node) &&
      node.name.getText(source) === declaration &&
      node.initializer &&
      ts.isObjectLiteralExpression(node.initializer)
    ) {
      for (const entry of node.initializer.properties) {
        if (
          !ts.isPropertyAssignment(entry) ||
          !ts.isStringLiteral(entry.name) ||
          !ts.isObjectLiteralExpression(entry.initializer)
        )
          continue;
        const translations = {};
        for (const value of entry.initializer.properties) {
          if (
            !ts.isPropertyAssignment(value) ||
            !ts.isStringLiteral(value.initializer)
          )
            throw new Error(`Non-literal translation in ${file}`);
          translations[
            ts.isStringLiteral(value.name)
              ? value.name.text
              : value.name.getText(source)
          ] = value.initializer.text;
        }
        messages.set(entry.name.text, translations);
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
}
const kotlin = (value) => JSON.stringify(value).replaceAll("$", "\\$");
const lines = [
  "package com.cleanhub.pos.nativepos",
  "",
  "// Generated by scripts/generate-native-pos-error-copy.mjs. Edit the shared i18n catalogue.",
];
for (const [locale, suffix] of [
  ["fr", "FR"],
  ["zh-CN", "ZH"],
]) {
  lines.push(
    `private val NATIVE_API_ERRORS_${suffix}: Map<String, String> = mapOf(`,
  );
  for (const [source, values] of [...messages].sort(([a], [b]) =>
    a.localeCompare(b, "en"),
  )) {
    if (!values[locale]) throw new Error(`Missing ${locale}: ${source}`);
    lines.push(`    ${kotlin(source)} to ${kotlin(values[locale])},`);
  }
  lines.push(")", "");
}
lines.push(
  "internal fun nativeApiErrorTranslations(language: String): Map<String, String> = when (language) {",
  '    "fr" -> NATIVE_API_ERRORS_FR',
  '    "zh-CN" -> NATIVE_API_ERRORS_ZH',
  "    else -> emptyMap()",
  "}",
  "",
);
const expected = lines.join("\n");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(output) || fs.readFileSync(output, "utf8") !== expected) {
    console.error(
      "Native API error translations are stale. Run node scripts/generate-native-pos-error-copy.mjs",
    );
    process.exitCode = 1;
  } else
    console.log(
      `Native API error translations are current (${messages.size} messages).`,
    );
} else {
  fs.writeFileSync(output, expected);
  console.log(
    `Generated native API error translations (${messages.size} messages).`,
  );
}
